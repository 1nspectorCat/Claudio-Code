package com.vladiko.voicebridge

import android.app.Activity
import android.os.Bundle

// v0.56 — ТРЕТИЙ КАНАЛ КНОПКИ ГАРНИТУРЫ (эксперимент по скрину журнала 30.07).
// Факт со скрина: во сне нажатие доходит («медиасобытие дошло до рации», «кнопка: код 127»),
// а во время диктовки (sco=true) НЕ доходит ни одного события — ни медиа, ни HFP-канала,
// хотя беззвучный keepalive играет и «кнопка держится=true». Значит в разговорном профиле
// нажатие перехватывает сама гарнитура/система и трактует его как запуск голосового
// ассистента (юзер слышит «тыкдык» в ухе, в телефон — ничего).
// Ловим ровно этот путь: регистрируемся получателем ACTION_VOICE_COMMAND. Если система
// на нажатие поднимает ассистента, поднимут НАС — и мы отдадим это рации как кнопку.
// Активность без UI: сразу отдаёт событие и закрывается.
class VoiceCmdActivity : Activity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        LogBus.add("кнопка (канал ассистента): пришёл ${intent?.action}")
        BridgeService.instance?.onButton()
        finish()
    }
}
